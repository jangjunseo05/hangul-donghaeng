"""Real-model smoke for phase 2 paths through a running local broker + worker.

PLAN ONLY until the orchestrator opens the L40S model tunnel (127.0.0.1:8001) and says go.
Without --run this prints the plan and makes no network call.

Topology (local-dev, NOT OpenShell):
  browser-API client (this script) -> broker 127.0.0.1:8000 (python -m service)
  -> worker (python -m agent.worker, RUN_CONTEXT=local-dev) -> SSH tunnel 127.0.0.1:8001 -> L40S vLLM.
The broker itself calls OSM (Nominatim <=1 rps, Overpass) and Wikipedia (serial) for real.
An OpenShell run instead uses infra/launch_worker.py with a policy regenerated by
infra/render_policy.py (adds /worker/progress and /worker/wiki; decision M3-2: next deploy).

Start (separate shells, WSL, secrets only in .env / shell env, never on the command line):
  1. orchestrator: GPU_SSH_ALIAS=hangul-l40s infra/open_model_tunnel.sh
  2. broker: .venv/bin/python -m service
  3. worker: NVIDIA_BASE_URL=http://127.0.0.1:8001/v1 NVIDIA_MODEL=nvidia/NVIDIA-Nemotron-Nano-12B-v2-VL-BF16 \
             NVIDIA_ALLOW_UNAUTHENTICATED_LOCAL=true RUN_CONTEXT=local-dev .venv/bin/python -u -m agent.worker
  4. python -B infra/smoke_live.py --run
Steps: observe with location, observe without location, ask (catalog place, prepared card),
external OSM place card (nearby landmark tab -> confirm -> Wikipedia -> model card), TTS fallback.
Results go to .runtime/smoke/ (ignored). A smoke pass is not a quality evaluation.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import sys
import time

import httpx

ROOT = Path(__file__).resolve().parents[1]
PHOTO = ROOT / "data" / "samples" / "heritage-demo.jpg"  # Gwanghwamun at night, CC0 (heritage-license.json)
GATE = {"lat": 37.5760179589004, "lng": 126.976788008924, "origin": "selected"}
TERMINAL = {"completed", "failed", "superseded"}
POLL_LIMIT_S = 75.0
PLAN = [
    ("observe_with_location", "observe frame + Gwanghwamun map point -> GPS candidates + closed-set choice"),
    ("observe_without_location", "same frame, no location -> free recognition"),
    ("ask_catalog_place", "confirmed local:gwanghwamun -> grounded answer + prepared landmark_card"),
    ("external_place_card", "GET /api/nearby landmark -> first osm:* place -> Wikipedia -> model 4-block card"),
    ("tts", "POST /api/tts -> 200 audio when Magpie is configured, else 503 TTS_UNAVAILABLE (browser fallback)"),
]


def request_body(session_id: str, **changes) -> dict:
    return {"schema_version": 1, "session_id": session_id, "question": "What am I looking at?", "photo_id": None,
            "dataset_mode": "real_place", "response_language": "en", "location": GATE, "radius_m": 1000,
            "confirmed_food_id": None, "confirmed_shop_id": None, **changes}


def run_job(client: httpx.Client, body: dict) -> dict:
    started = time.perf_counter()
    created = client.post("/api/requests", json=body)
    if created.status_code != 202:
        return {"http_status": created.status_code, "error_code": created.json().get("error_code")}
    poll_url, stages, status = created.json()["poll_url"], [], {}
    while time.perf_counter() - started < POLL_LIMIT_S:
        status = client.get(poll_url).json()
        if status.get("stage") and (not stages or stages[-1] != status["stage"]):
            stages.append(status["stage"])
        if status["status"] in TERMINAL:
            break
        time.sleep(0.5)
    return {"latency_s": round(time.perf_counter() - started, 2), "status": status.get("status"),
            "error_code": status.get("error_code"), "stages": stages, "result": status.get("result")}


def summary(outcome: dict) -> dict:
    result = outcome.pop("result", None) or {}
    scene = result.get("scene") or {}
    card = result.get("landmark_card")
    outcome.update({
        "result_status": result.get("status"), "speech_text": result.get("speech_text"),
        "observed_place_name": scene.get("observed_place_name"),
        "observed_place_source": scene.get("observed_place_source"),
        "observed_place_confidence": scene.get("observed_place_confidence"),
        "place_candidates": [item["id"] for item in scene.get("place_candidates", [])],
        "claims": len(result.get("claims", [])), "evidence_ids": [item["id"] for item in result.get("evidence", [])],
        "card": None if not card else {
            "place_id": card["place_id"], "verification": card["verification"],
            "blocks": {key: (value or {}).get("verification") for key, value in card["blocks"].items()},
            "sources": [source["url"] for source in card.get("sources", [])]},
    })
    return outcome


def main(argv=None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--broker", default="http://127.0.0.1:8000")
    parser.add_argument("--run", action="store_true", help="Call the running broker (real model, OSM, Wikipedia).")
    parser.add_argument("--out", type=Path, default=ROOT / ".runtime" / "smoke")
    args = parser.parse_args(argv)
    if not args.run:
        for name, description in PLAN:
            print(f"PLAN {name}: {description}")
        print("NOT_RUN: pass --run after the orchestrator opens the model tunnel and broker+worker are up.")
        return 0
    report = {"started_at": datetime.now(timezone.utc).isoformat(), "broker": args.broker,
              "topology": "local-dev worker (not OpenShell)", "steps": {}}
    with httpx.Client(base_url=args.broker, timeout=20.0, trust_env=False, follow_redirects=False) as client:
        health = client.get("/api/health").json()
        report["health"] = health
        if not health.get("worker_connected"):
            print("worker not connected; start agent.worker first", file=sys.stderr)
            return 2
        created = client.post("/api/sessions", json={})
        if created.status_code != 200:
            print(f"session refused: {created.status_code} {created.json().get('error_code')}", file=sys.stderr)
            return 2
        session_id = created.json()["session_id"]

        def frame() -> str:
            with PHOTO.open("rb") as handle:
                return client.post("/api/photos", files={"file": ("frame.jpg", handle, "image/jpeg")},
                                   data={"purpose": "observe"}).json()["photo_id"]

        steps = report["steps"]
        steps["observe_with_location"] = summary(run_job(client, request_body(
            session_id, photo_id=frame(), interaction_mode="observe")))
        steps["observe_without_location"] = summary(run_job(client, request_body(
            session_id, photo_id=frame(), interaction_mode="observe", location=None)))
        steps["ask_catalog_place"] = summary(run_job(client, request_body(
            session_id, confirmed_place_id="local:gwanghwamun", question="Tell me the story of this gate.")))
        started = time.perf_counter()
        nearby = client.get("/api/nearby", params={"tab": "landmark", "lat": GATE["lat"], "lng": GATE["lng"],
                                                   "radius_m": 1000}, timeout=30.0).json()
        external = next((place for place in nearby.get("places", []) if place["place_id"].startswith("osm:")), None)
        steps["nearby_landmark"] = {"latency_s": round(time.perf_counter() - started, 2),
                                    "error_code": nearby.get("error_code"), "places": len(nearby.get("places", [])),
                                    "osm_places": sum(p["place_id"].startswith("osm:") for p in nearby.get("places", []))}
        if external:
            steps["external_place_card"] = {"place_id": external["place_id"], "name": external["name"],
                **summary(run_job(client, request_body(session_id, confirmed_place_id=external["place_id"],
                                                       question="Tell me about this place.")))}
        else:
            steps["external_place_card"] = {"skipped": "no OSM landmark returned"}
        started = time.perf_counter()
        speech = client.post("/api/tts", json={"text": "Welcome to Gyeongbokgung (the main palace).", "lang": "en"})
        steps["tts"] = {"http_status": speech.status_code, "latency_s": round(time.perf_counter() - started, 2),
                        "content_type": speech.headers.get("content-type"),
                        "error_code": None if speech.status_code == 200 else speech.json().get("error_code")}
    report["finished_at"] = datetime.now(timezone.utc).isoformat()
    args.out.mkdir(parents=True, exist_ok=True)
    path = args.out / f"smoke-{datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')}.json"
    path.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps(report, ensure_ascii=False, indent=2))
    print("REPORT", path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
